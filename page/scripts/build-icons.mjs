#!/usr/bin/env node
// Builds assets/icons.svg, the one sprite every page uses, from pinned packages: Simple Icons (CC0-1.0) for
// platform marks and Lucide (ISC) for generic glyphs. `--check` fails if the committed sprite is stale.
//   node page/scripts/build-icons.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const here = dirname(new URL(import.meta.url).pathname)
const root = resolve(here, '../..')
// The packages' own directories (some do not export package.json, so resolve by path).
const pkgDir = (name) => join(root, 'page', 'node_modules', name)

// Sprite id (the manifest's icon name) -> [source, file]. Must list exactly crates/core/src/icons.rs.
const ICONS = {
  x: ['si', 'x'], mastodon: ['si', 'mastodon'], bluesky: ['si', 'bluesky'], github: ['si', 'github'],
  gitlab: ['si', 'gitlab'], codeberg: ['si', 'codeberg'], huggingface: ['si', 'huggingface'],
  youtube: ['si', 'youtube'], matrix: ['si', 'matrix'], discord: ['si', 'discord'], telegram: ['si', 'telegram'],
  nostr: ['lu', 'zap'], instagram: ['si', 'instagram'], tiktok: ['si', 'tiktok'], twitch: ['si', 'twitch'],
  reddit: ['si', 'reddit'], sui: ['si', 'sui'], npm: ['si', 'npm'],
  link: ['lu', 'link'], mail: ['lu', 'mail'], website: ['lu', 'globe'], docs: ['lu', 'book-open'],
  code: ['lu', 'code'], package: ['lu', 'package'], rss: ['lu', 'rss'], heart: ['lu', 'heart'],
  // Used by the page itself, not choosable in a manifest.
  chevron: ['lu', 'chevron-down'],
}

const dirs = { si: join(pkgDir('simple-icons'), 'icons'), lu: join(pkgDir('lucide-static'), 'icons') }
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/, '').replace(/<!--[\s\S]*?-->/g, '').trim()

const symbols = Object.entries(ICONS).map(([id, [src, file]]) => {
  const body = inner(readFileSync(join(dirs[src], `${file}.svg`), 'utf8'))
  const paint = src === 'si'
    ? 'fill="currentColor"'
    : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
  return `<symbol id="i-${id}" viewBox="0 0 24 24"><g ${paint}>${body}</g></symbol>`
})
const versions = ['simple-icons', 'lucide-static'].map((p) => `${p}@${JSON.parse(readFileSync(join(pkgDir(p), 'package.json'), 'utf8')).version}`)
const out = `<svg xmlns="http://www.w3.org/2000/svg"><!-- Generated by page/scripts/build-icons.mjs from ${versions.join(', ')} (CC0-1.0, ISC). Do not edit. -->\n${symbols.join('\n')}\n</svg>\n`

const target = join(root, 'assets', 'icons.svg')
if (process.argv.includes('--check')) {
  let cur = ''
  try { cur = readFileSync(target, 'utf8') } catch {}
  if (cur !== out) { console.error('assets/icons.svg is stale: run node page/scripts/build-icons.mjs'); process.exit(1) }
  console.log('icons: OK')
} else {
  writeFileSync(target, out)
  console.log(`wrote assets/icons.svg (${symbols.length} icons)`)
}
